/* ── ENGINE ── */
function bI18nGet(lang, page, key) {
  const t = BOREALIS_T[lang];
  if (!t) return null;
  return (t[page] && t[page][key] !== undefined) ? t[page][key]
       : (t.common && t.common[key] !== undefined) ? t.common[key]
       : null;
}

function bI18nApply(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const [page, key] = el.dataset.i18n.split('.');
    const val = bI18nGet(lang, page, key);
    if (val === null) return;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else if (el.tagName === 'OPTION') {
      el.textContent = val;
    } else {
      el.innerHTML = val;
    }
  });
  document.documentElement.lang = lang === 'ru' ? 'ru' : lang === 'fr' ? 'fr' : lang === 'es' ? 'es' : 'en';
  // update lang button label
  const btn = document.getElementById('langBtn');
  if (btn) btn.textContent = lang.toUpperCase();
  // mark active
  document.querySelectorAll('.lang-drop button[data-lang]').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
}

function bI18nSetLang(lang) {
  localStorage.setItem('borealis_lang', lang);
  bI18nApply(lang);
  const drop = document.getElementById('langDrop');
  if (drop) drop.classList.remove('open');
}

function bI18nToggleDrop() {
  const drop = document.getElementById('langDrop');
  if (drop) drop.classList.toggle('open');
}

function bI18nInit() {
  const saved = localStorage.getItem('borealis_lang');
  const lang = saved || 'en';
  bI18nApply(lang);
  // close on outside click
  document.addEventListener('click', e => {
    if (!e.target.closest('#langSw')) {
      const drop = document.getElementById('langDrop');
      if (drop) drop.classList.remove('open');
    }
  });
}

document.addEventListener('DOMContentLoaded', bI18nInit);
